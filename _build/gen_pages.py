# ==================================================================== helpers
def svc_cards(depth, exclude=None, cls="cb-cards cb-cards--3"):
    r = rel(depth)
    out = []
    for s in SERVICES:
        if s["slug"] == exclude:
            continue
        out.append(
            f'<a class="cb-card" href="{r}{s["slug"]}" data-reveal>'
            f'<span class="cb-card__ic">{icon(s["icon"], "w-7 h-7")}</span>'
            f'<span class="cb-card__t">{s["short"]}</span>'
            f'<span class="cb-card__d">{s["teaser"]}</span>'
            f'<span class="cb-card__more">Περισσότερα <span>&#8594;</span></span></a>'
        )
    return f'<div class="{cls}">' + "".join(out) + "</div>"


def related_chips(depth, exclude):
    r = rel(depth)
    links = "".join(f'<a class="cb-chip" href="{r}{s["slug"]}">{s["nav"]}</a>'
                    for s in SERVICES if s["slug"] != exclude)
    return f'<div class="cb-chips">{links}</div>'


def facts(rows):
    return '<ul class="cb-facts">' + "".join(
        f"<li><b>{k}</b><span>{v}</span></li>" for k, v in rows) + "</ul>"


def aside(depth, extra=""):
    return f'<aside class="cb-aside">{contact_card(depth)}{extra}</aside>'


def timeline(rows):
    """rows: [(περίοδος, τίτλος, περιγραφή)]"""
    return '<ul class="cb-time">' + "".join(
        f'<li><span class="cb-time__k">{k}</span><span class="cb-time__t">{t}</span>'
        f'<span class="cb-time__d">{d}</span></li>' for k, t, d in rows) + "</ul>"


def simple_list(rows):
    """rows: [(έτος, τίτλος, φορέας)]"""
    return '<ul class="cb-list">' + "".join(
        f"<li><b>{y}</b><span>{t}<em>{f}</em></span></li>" for y, t, f in rows) + "</ul>"


