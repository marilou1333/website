def thread_svg():
    """Ένα ενιαίο νήμα: κουβάρι → ευθεία → σπείρα, όπως στο λογότυπο.
    Το κουβάρι είναι καμπύλη Lissajous με σχεδόν άρρητη σχέση συχνοτήτων, ώστε
    να μην κλείνει ποτέ στον εαυτό της και να διαβάζεται ως μπερδεμένο νήμα.
    Η σπείρα είναι αρχιμήδεια, ελαφρώς πεπλατυσμένη όπως στην κάρτα."""
    import math
    CY = 130.0

    def tangle(cx=120.0, rx=82.0, ry=64.0, turns=7, n=560):
        pts = []
        for i in range(n + 1):
            t = 2 * math.pi * turns * i / n
            x = cx + rx * math.sin(1.00 * t + 0.6) * (0.70 + 0.30 * math.cos(0.29 * t))
            y = CY + ry * math.sin(1.47 * t + 1.1) * (0.72 + 0.28 * math.sin(0.19 * t))
            pts.append((x, y))
        return pts

    def spiral(cx=1094.0, turns=3.9, r0=6.0, r1=88.0, n=380):
        pts = []
        for i in range(n + 1):
            u = i / n
            a = 2 * math.pi * turns * u
            r = r0 + (r1 - r0) * u
            pts.append((cx + r * math.cos(a + math.pi), CY + r * 0.92 * math.sin(a + math.pi)))
        return pts

    tg, sp = tangle(), spiral()
    pts = tg + [(tg[-1][0], CY), (sp[0][0], CY)] + sp
    d = "M" + " L".join("%.1f,%.1f" % p for p in pts)

    # Μήκος διαδρομής, για σωστό dasharray χωρίς getTotalLength() στον browser.
    L = sum(math.dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1))
    L = int(L) + 10

    # Το νήμα σχεδιάζεται σιγά σιγά, από το κουβάρι προς τη σπείρα: ξετυλίγεται,
    # μένει λίγο ολόκληρο, μετά σβήνει με την ίδια φορά και ξαναρχίζει.
    # Με prefers-reduced-motion μένει μόνιμα σχεδιασμένο, χωρίς κίνηση.
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 260" '
        'width="1200" height="260" role="presentation">'
        '<style>'
        'path{fill:none;stroke:#8fd0bc;stroke-width:1.5;'
        'stroke-linecap:round;stroke-linejoin:round;'
        f'stroke-dasharray:{L};stroke-dashoffset:{L};'
        'animation:draw 24s ease-in-out infinite}'
        f'@keyframes draw{{0%{{stroke-dashoffset:{L}}}'
        f'40%{{stroke-dashoffset:0}}78%{{stroke-dashoffset:0}}'
        f'100%{{stroke-dashoffset:-{L}}}}}'
        '@media (prefers-reduced-motion:reduce){'
        'path{animation:none;stroke-dashoffset:0}}'
        '</style>'
        f'<path d="{d}"/></svg>'
    )


